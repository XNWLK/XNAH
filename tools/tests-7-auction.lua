	W.mine(2589, 95, 5)
	X.SetWatchMax("2589", 60)
	X.ShopAdd("Mats", "2589", 10, 95)
	W.openAH()
	local used = 0
	local function useBoxes(root)
		W.walk(root, function(f)
			if f.kind == "EditBox" and f:IsVisible() then
				for _, text in ipairs({"lin", "10g 5s", "15", "zzz", ""}) do
					W.type(f, text)
					W.advance(0.3)
					used = used + 1
				end
				if f.scripts.OnEditFocusLost then W.step(f.scripts.OnEditFocusLost, f) end
			end
		end)
	end
	local p = tab(X, "sell", "Post by hand")
	W.click("Linen Cloth", p.sellTable)
	W.advance(2)
	useBoxes(p)
	for _, d in ipairs({"2h", "8h", "24h"}) do W.click(d, p) end
	W.click("Suggested", p)
	W.click("Back to the general rules", p)
	W.click("Search again", p)
	W.advance(2)
	W.click("Raider Shortsword", p.sellTable)
	W.advance(2)
	useBoxes(p)
	W.click("Undercut auctions", p)
	W.click("Check auctions", p)
	W.advance(5)
	W.click("Post by hand", p)
	p = tab(X, "buy", "Shopping lists and sniper")
	W.click("Linen Cloth", p.shopTable)
	W.advance(2)
	useBoxes(p)
	W.click("Linen Cloth", p.watchTable)
	useBoxes(p)
	W.click("Search list", p)
	W.click("Search again", p)
	W.advance(3)
	W.click("Clear", p)
	W.advance(1)
	T.ok("boxes used", used >= 20, used)
	T.check("no restricted call from boxes and helper buttons", #W.restrictedCalls, 0)
	W.closeAH()
	W.advance(1)
	X.UI.Refresh(true)
	tab(X, "sell")
