-- buys or cancels ever runs outside a click (tools/world-auction.lua makes those calls throw an error outside one).

-- days of price history: the usual price of an item becomes `usual`
local function history(X, key, usual, days)
	for d = days or 5, 1, -1 do X.Record(key, X.Now() - d * 86400, usual, usual, 50, 5) end
end
-- opens a tab (and one of its views: the text of its view button)
local function tab(X, key, view)
	X.UI.Open(key)
	W.advance(0.5)
	local p = X.UI.tabs[key].panel
	if view then W.click(view, p) W.advance(0.3) end
	return p
end
local function myAuctions(id)
	local out = {}
	for _, a in ipairs(W.ah) do if a.owner == W.me and (not id or a.itemID == id) then out[#out + 1] = a end end
	return out
end
local function count(id, unit)
	local n = 0
	for _, a in ipairs(W.ah) do if a.itemID == id and (not unit or W.unitOf(a) == unit) then n = n + a.count end end
	return n
end
local function bagCount(id)
	local n = 0
	for _, bag in pairs(W.bags) do for _, s in pairs(bag) do if s.id == id then n = n + s.count end end end
	return n
end
local function searchNow(X, key)
	local got
	X.LiveSearch(key, function(live) got = live end)
	W.waitFor(function() return got ~= nil end, 10)
	return got
end

T.scene("auction: price rules (undercut, floor, ceiling, own auction ignored)", function()
	local X = W.start()
	history(X, "2589", 100)
	T.near("usual price 1s", X.Usual("2589"), 100, 0.01)
	W.list(2589, 90, 20, 2, "Ann")
	W.mine(2589, 85, 10)
	W.openAH()
	local live = searchNow(X, "2589")
	T.check("search: lowest not ours", live and live.lowest, 90)
	T.check("search: our own lowest seen apart", live and live.ownLowest, 85)
	T.check("search: our 10 are not counted as offers", live and live.qty, 40)
	local p, why = X.PostPrice("2589")
	T.check("undercut by 1c (our own 85c auction ignored)", p, 89)
	T.ok("reason says undercut", why and why:find("undercut 90c by 1c", 1, true), why)
	-- the cheapest is under the floor (80% of 1s): the usual price, not chasing it down
	W.list(2589, 70, 5, 1, "Low")
	searchNow(X, "2589")
	p, why = X.PostPrice("2589")
	T.check("under the floor: usual price", p, X.Round(X.PostUsual("2589")))
	T.ok("reason says floor", why and why:find("floor", 1, true), why)
	-- everything far over the usual: the ceiling (200%)
	W.ah = {}
	W.list(2589, 300, 20, 1, "High")
	searchNow(X, "2589")
	p, why = X.PostPrice("2589")
	T.check("over the ceiling: 200% of usual", p, X.Round(X.PostUsual("2589") * 2))
	T.ok("reason says ceiling", why and why:find("ceiling", 1, true), why)
	-- nobody else sells it (only us)
	W.ah = {}
	W.mine(2589, 95, 10)
	searchNow(X, "2589")
	p, why = X.PostPrice("2589")
	T.check("nobody else: usual price", p, X.Round(X.PostUsual("2589")))
	T.ok("reason says nobody else", why and why:find("nobody else", 1, true), why)
	-- the item's own rules
	W.ah = {}
	W.list(2589, 90, 20, 1, "Ann")
	searchNow(X, "2589")
	X.SetPostRule("2589", "undercut", 5)
	T.check("own rule: undercut by 5c", (X.PostPrice("2589")), 85)
	X.SetPostRule("2589", "floor", 95)
	T.check("own rule: floor 95% -> usual price", (X.PostPrice("2589")), X.Round(X.PostUsual("2589")))
	T.ok("usual moved with today's searches (they are price points too)", X.PostUsual("2589") > 95, X.PostUsual("2589"))
	X.SetPostRule("2589", "normal", 120)
	T.check("own rule: normal price used under the floor", (X.PostPrice("2589")), 120)
	X.ResetPostRule("2589")
	T.check("back to the general rules", (X.PostPrice("2589")), 89)
	T.check("rules saved only when changed", X.db.postRules["2589"], nil)
	-- an auction house without copper: whole silver, undercut by 1s
	W.copperValues = false
	history(X, "4306", 10000)
	W.list(4306, 9000, 20, 1, "Ann")
	searchNow(X, "4306")
	T.check("no copper: undercut by 1s", (X.PostPrice("4306")), 8900)
	-- no search: the last scan's lowest (marked as possibly yours)
	W.copperValues = true
	X.live["2589"] = nil
	X.Record("2589", X.Now(), 93, 100, 20, 1)
	p, why = X.PostPrice("2589")
	T.check("no search: from the scan", p, 92)
	T.ok("reason says last scan", why and why:find("last scan", 1, true), why)
	T.check("nothing restricted was called", #W.restrictedCalls, 0)
end)

