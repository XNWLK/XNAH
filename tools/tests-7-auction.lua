T.scene("auction: cancel scan finds an undercut auction", function()
	local X = W.start()
	local a = W.mine(2589, 95, 10)       -- undercut by Ann at 90c
	W.mine(2592, 50, 10)                 -- not undercut (others at 60c)
	W.list(2589, 90, 20, 1, "Ann")
	W.list(2592, 60, 20, 1, "Bob")
	W.cancelCost = 25
	W.openAH()
	-- the Sell tab opens on Worth posting: with the auction house open, its round starts and checks your auctions
	local p = tab(X, "sell", "Undercut auctions")
