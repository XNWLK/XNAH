T.scene("auction: nothing restricted is called outside a click", function()
	local X = W.start()
	history(X, "2589", 100)
	W.putBag(0, 1, 2589, 20)
	W.mine(2589, 95, 10)
	W.list(2589, 50, 20, 3, "Ann")
	W.list(15210, 50000, 1, 1, "Dan", -19)
