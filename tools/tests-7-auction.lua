	W.waitFor(function() return X.cancel.state == "done" end, 20)
	W.advance(1) -- the window catches up (its refresh waits a moment after the last change)
	W.click("Check auctions", p)
	W.waitFor(function() return X.cancel.state == "done" end, 20)
	T.check("cancel scan done", X.cancel.state, "done")
	T.check("both auctions seen", #X.cancel.all, 2)
	T.check("one is undercut", #X.cancel.rows, 1)
	local r = X.cancel.rows[1]
	T.check("undercut: Linen", r and r.key, "2589")
	T.check("your price", r and r.unit, 95)
	T.check("lowest now", r and r.lowest, 90)
	T.check("cancel cost", r and r.cost, 25)
	T.check("searched one by one, about a second apart", #W.searches, 2)
	T.ok("searches throttled", W.searches[2] and W.searches[2].t - W.searches[1].t >= 0.99, W.searches[2] and (W.searches[2].t - W.searches[1].t))
