	T.check("the other stays", #myAuctions(2592), 1)
	T.check("restricted calls", table.concat(W.restrictedCalls, ","), "CancelAuction")
	T.check("list empty now", #X.cancel.rows, 0)
	T.ok("items come back", W.returned[1] and W.returned[1].id == 2589 and a.count == 10)
end)

