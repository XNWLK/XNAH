	local frame = X.UI.Frame()
	X.S().goldView = "items"
	X.UI.Select("ledger") -- the old name opens the Gold tab
	W.advance(1)
	T.check("ledger opens the gold tab", X.UI.current, "gold")
	local text = W.screen(frame)
	T.ok("by item: the item", text:find("Linen Cloth", 1, true) ~= nil, text)
	T.ok("by item: the help line", text:find("auction house mails", 1, true) ~= nil)
	W.click("Recent", frame)
	W.advance(1)
	text = W.screen(frame)
	T.ok("recent: sold", text:find("sold", 1, true) ~= nil)
	T.ok("recent: expired", text:find("expired", 1, true) ~= nil)
	W.click("Overview", frame)
	W.advance(1)
	text = W.screen(frame)
	T.ok("overview: totals", text:find("Gold per hour", 1, true) ~= nil, text)
	T.ok("overview: weekly chart", text:find("Profit per week", 1, true) ~= nil)
