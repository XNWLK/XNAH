-- XNAH test scenes, part 6: the sales ledger (auction house mails) and the inventory / net worth of your characters.

local function L(X) return X.Ledger() end
local function n(list) return #(list or {}) end

T.scene("ledger: sold, bought, expired and cancelled mails are recorded once", function()
	local X = W.start()
	W.advance(5)
	W.addMail(W.mailSold(2589, 1000, 20, "Ann Lee", 50))
	W.addMail(W.mailWon(2592, 400, 10, "Bob Stone"))
	W.addMail(W.mailExpired(2770, 5))
	W.addMail(W.mailCancelled(3576, 2))
	W.addMail(W.mailExpired(15210, 1, -19))
	W.addMail({sender = "Ann Lee", subject = "thanks", money = 500}) -- not an auction mail
	W.openMail()
	local l = L(X)
	T.check("one sale", n(l.sales), 1)
	T.check("one purchase", n(l.buys), 1)
	T.check("two expired", n(l.expired), 2)
	T.check("one cancelled", n(l.cancelled), 1)
	local s = l.sales[1]
	T.check("sale: item key from the name", s and s.key, "2589")
	T.check("sale: price", s and s.money, 1000)
	T.check("sale: cut", s and s.cut, 50)
	T.check("sale: count", s and s.count, 20)
	T.check("sale: buyer", s and s.who, "Ann Lee")
	T.check("sale: character", s and s.char, "Xn Ascalon")
	T.check("purchase: key from the attached item", l.buys[1] and l.buys[1].key, "2592")
	T.check("purchase: seller", l.buys[1] and l.buys[1].who, "Bob Stone")
	T.check("cancelled: Tin Bar (the game writes 'canceled')", l.cancelled[1] and l.cancelled[1].key, "3576")
	T.check("cancelled: count", l.cancelled[1] and l.cancelled[1].count, 2)
	local sword
	for _, e in ipairs(l.expired) do if e.key == "15210:-19" then sword = e end end
	T.ok("expired sword: key with its suffix", sword ~= nil)
	-- the mailbox read again and again, over hours
	for i = 1, 4 do
		W.fire("MAIL_INBOX_UPDATE")
		W.advance(1)
		W.closeMail()
		W.advance(3600)
		W.openMail()
	end
	l = L(X)
	T.check("read 5 times: still one sale", n(l.sales), 1)
	T.check("read 5 times: still one purchase", n(l.buys), 1)
	T.check("read 5 times: still two expired", n(l.expired), 2)
	-- after a reload
	X = W.reload()
	W.advance(5)
	W.openMail()
	l = L(X)
	T.check("after a reload: still one sale", n(l.sales), 1)
	T.check("after a reload: still one cancelled", n(l.cancelled), 1)
	-- the same sale again (same buyer and price), later: a second sale
	W.addMail(W.mailSold(2589, 1000, 20, "Ann Lee", 50))
	W.advance(2)
	T.check("an equal sale later: two sales", n(L(X).sales), 2)
	-- two equal sales arriving together: both count
	W.advance(7200)
	W.addMail(W.mailSold(2592, 300, 5, "Cid Moss", 15))
	W.addMail(W.mailSold(2592, 300, 5, "Cid Moss", 15))
	W.advance(2)
	T.check("two equal sales at once: both count", n(L(X).sales), 4)
	W.fire("MAIL_INBOX_UPDATE")
	W.advance(2)
	T.check("and still 4 when read again", n(L(X).sales), 4)
	-- one of the two taken: the other is not counted again
	for _, m in ipairs(W.mail) do
		if m.invoice and m.invoice.player == "Cid Moss" then W.takeMail(m) break end
	end
	W.advance(2)
	T.check("one of two equal mails taken: still 4", n(L(X).sales), 4)
	local tot = X.LedgerTotals()
	T.check("income after the cut", tot.income, 950 * 2 + 285 * 2)
	T.check("spent", tot.spent, 400)
	T.check("cut", tot.cut, 50 * 2 + 15 * 2)
	T.check("profit", tot.profit, 950 * 2 + 285 * 2 - 400)
	T.check("sale mails", tot.sales, 4)
	T.check("totals of the last hour: only the newest", X.LedgerTotals(X.Now() - 3600).sales, 2)
	T.ok("saved data", W.savedSize() > 0)
end)

T.scene("ledger: a sale pending and then its real invoice count once", function()
	local X = W.start()
	W.advance(5)
	local p = W.addMail(W.mailPending(2589, 2000, 20, "Cid Moss", 100))
	W.openMail()
	local l = L(X)
	T.check("pending sale recorded", n(l.sales), 1)
	T.check("marked as money on the way", l.sales[1] and l.sales[1].pending, true)
	T.check("pending counts as income", X.LedgerTotals().income, 1900)
	-- an hour later the real invoice comes, the pending mail goes
	W.advance(3600)
	W.takeMail(p)
	W.addMail(W.mailSold(2589, 2000, 20, "Cid Moss", 100))
	W.advance(2)
	l = L(X)
	T.check("real invoice: still one sale", n(l.sales), 1)
	T.check("real invoice: no longer pending", l.sales[1] and l.sales[1].pending, nil)
	T.check("real invoice: cut", l.sales[1] and l.sales[1].cut, 100)
	T.check("income not doubled", X.LedgerTotals().income, 1900)
	X = W.reload()
	W.advance(5)
	W.openMail()
	T.check("after a reload: one sale", n(L(X).sales), 1)
	-- both mails in the box at once (the newer real one is read first)
	W.advance(86400)
	local p2 = W.addMail(W.mailPending(2592, 600, 10, "Dee Fox", 30))
	W.advance(3600)
	W.addMail(W.mailSold(2592, 600, 10, "Dee Fox", 30))
	W.advance(2)
	T.check("pending and real together: one more sale", n(L(X).sales), 2)
	W.takeMail(p2)
	W.advance(2)
	T.check("pending mail taken: still two", n(L(X).sales), 2)
	T.check("income", X.LedgerTotals().income, 1900 + 570)
end)

T.scene("ledger: numbers per item, per day, unknown names", function()
	local X = W.start()
	W.advance(5)
	W.addMail(W.mailSold(2589, 2000, 20, "Ann Lee", 100))
	W.addMail(W.mailSold(2589, 1200, 10, "Bob Stone", 60))
	W.addMail(W.mailWon(2589, 2000, 40, "Cid Moss"))
	W.addMail(W.mailExpired(2589, 20))
	W.addMail(W.mailCancelled(2589, 10))
	W.addMail({sender = "Auction House", subject = "Auction successful: Mystery Thing", money = 950,
		invoice = {type = "seller", itemName = "Mystery Thing", player = "Eve", bid = 1000, consignment = 50, deposit = 0, count = 1}})
	W.openMail()
	local li = X.LedgerItem("2589")
	T.ok("Linen in the ledger", li ~= nil)
	if li then
		T.check("sold", li.sold, 30)
		T.check("sold value after the cut", li.soldValue, 1900 + 1140)
		T.check("bought", li.bought, 40)
		T.check("bought value", li.boughtValue, 2000)
		T.check("expired", li.expired, 20)
		T.check("cancelled", li.cancelled, 10)
		T.near("sell-through 30 of 60", li.sellThrough, 0.5, 0.001)
		T.near("average sale", li.avgSell, 3040 / 30, 0.01)
		T.check("average buy", li.avgBuy, 50)
		T.check("profit: sales minus what the 30 sold cost", li.profit, 3040 - 50 * 30)
	end
	T.check("never traded: nil", X.LedgerItem("2592"), nil)
	-- an item the game did not know: kept by name, found once the item is known
	local mystery
	for _, e in ipairs(L(X).sales) do if e.name == "Mystery Thing" then mystery = e end end
	T.ok("unknown item kept by name", mystery ~= nil and mystery.key == nil)
	W.items[900500] = {name = "Mystery Thing", quality = 2, sell = 10, stack = 1}
	local m = X.LedgerItem("900500")
	T.check("found by name later", m and m.sold, 1)
	T.check("its value", m and m.soldValue, 950)
	local rows = X.LedgerByItem()
	T.check("by item: two rows", #rows, 2)
	local recent = X.LedgerRecent(3)
	T.check("recent: limited to 3", #recent, 3)
	local days = X.LedgerDays(30)
	T.check("30 days", #days, 30)
	T.check("today is last", days[30].day, X.Day())
	T.check("today's income", days[30].income, 1900 + 1140 + 950)
	T.check("today's spending", days[30].spent, 2000)
	T.check("yesterday: nothing", days[29].income, 0)
	T.near("sold per day: a ledger of one day", X.LedgerItem("2589").soldPerDay, 30, 0.001)
	W.advance(10 * 86400)
	T.near("sold per day: 30 units over the 10 days the ledger covers", X.LedgerItem("2589").soldPerDay, 3, 0.01)
	W.advance(30 * 86400)
	T.check("sold per day: nothing in the last 30 days", X.LedgerItem("2589").soldPerDay, 0)
	-- a year and a day later the entries are gone
	W.closeMail()
	W.mail = {}
	W.advance(366 * 86400)
	X = W.reload()
	W.advance(5)
	T.check("after a year: pruned", n(L(X).sales), 0)
	T.check("after a year: no fingerprints left", T.count(L(X).seen), 0)
end)

-- a small market: Linen 1s, Wool 30c (a vendor pays 33c), Runecloth 10s, Silk 3s
local function market(X)
	W.list(2589, 100, 20, 5)
	W.list(2592, 30, 20, 5)
	W.list(14047, 1000, 20, 5)
	W.list(4306, 300, 20, 5)
	W.openAH()
	T.ok("full scan", T.fullScan(X))
	W.closeAH()
end

T.scene("wealth: net worth with bound items, bank, account bank, mail and auctions", function()
	local X = W.start()
	W.fill(0, {{2589, 20}, {14047, 10, nil, true}, {2840, 3}})
	W.setMoney(100000)
	W.advance(10)
	market(X)
	W.fill(6, {{2592, 10}})
	W.fill(15, {{2589, 10}})
	W.openBank()
	W.closeBank()
	W.addMail(W.mailWon(2589, 500, 5, "Bob Stone"))
	W.addMail({sender = "Ann Lee", subject = "gold", money = 3000})
	W.openMail()
	W.closeMail()
	W.owned = {{itemID = 2589, count = 20, status = 0}, {itemID = 2592, count = 5, status = 1}}
	W.ownedChanged()
	local chars = X.Chars()
	T.check("one character", #chars, 1)
	local c = chars[1] or {}
	T.check("name", c.name, "Xn Ascalon")
	T.check("gold", c.gold, 100000)
	-- bags: 20 Linen at 95c after the cut, 10 bound Runecloth at the vendor's 4s (not the 10s auction price), 3 Copper Bars (no
	-- auction price) at the vendor's 10c
	T.near("bags", c.bags, 20 * 95 + 10 * 400 + 3 * 10)
	T.near("bank: 10 Wool at 28.5c", c.bank, 285)
	T.near("mail: 5 Linen and 30s", c.mail, 5 * 95 + 3000)
	T.near("auctions: 20 Linen (the sold one left out)", c.auctions, 20 * 95)
	T.near("total", c.worth, 100000 + 1900 + 4030 + 285 + 3475 + 1900)
	T.near("account bank", X.WarbankWorth(), 950)
	local total, parts = X.Owned(2589)
	T.check("owned Linen: total", total, 20 + 5 + 20 + 10)
	T.check("owned Linen: bags", parts.bags, 20)
	T.check("owned Linen: mail", parts.mail, 5)
	T.check("owned Linen: auctions", parts.auctions, 20)
	T.check("owned Linen: account bank", parts.warbank, 10)
	T.check("owned Wool: bank", select(2, X.Owned("2592")).bank, 10)
	-- bank closed: its contents are kept
	W.bagsChanged()
	T.check("bank kept after the bank closed", select(2, X.Owned(2592)).bank, 10)
	-- money changes
	W.setMoney(150000)
	W.advance(2)
	T.check("gold updated", X.Chars()[1].gold, 150000)
	-- net worth history: today's point
	W.advance(5)
	local h = X.WorthHistory(nil)
	T.check("one point of total worth", #h, 1)
	T.near("total worth includes the account bank", h[1] and h[1][2], 150000 + 1900 + 4030 + 285 + 3475 + 1900 + 950)
	T.check("own history", #X.WorthHistory("Xn Ascalon"), 1)
	-- next day: a second point
	W.advance(86400)
	W.setMoney(160000)
	W.advance(5)
	T.check("a day later: two points", #X.WorthHistory(nil), 2)
	X = W.reload()
	W.advance(10)
	T.check("after a reload: two points", #X.WorthHistory(nil), 2)
end)

T.scene("wealth: two characters, other realm, deleting one", function()
	local X = W.start()
	W.fill(0, {{2589, 10}})
	W.setMoney(10000)
	W.advance(10)
	-- log in with another character
	W.player, W.surname = "Ann", "Smith"
	W.bags = {}
	W.fill(0, {{2592, 5}})
	W.money = 20000
	X = W.reload()
	W.advance(10)
	local chars = X.Chars()
	T.check("two characters", #chars, 2)
	local mine
	for _, c in ipairs(chars) do if c.me then mine = c end end
	T.check("this one", mine and mine.name, "Ann Smith")
	T.check("this one's gold", mine and mine.gold, 20000)
	local total, parts = X.Owned(2589)
	T.check("Linen on the other character", parts.alts, 10)
	T.check("Linen in my bags", parts.bags, 0)
	T.check("Linen in total", total, 10)
	-- another realm: its characters are not shown
	W.realm = "Otherland"
	X = W.reload()
	W.advance(10)
	T.check("other realm: only this character", #X.Chars(), 1)
	W.realm = "Stormreach"
	X = W.reload()
	W.advance(10)
	T.check("back: two", #X.Chars(), 2)
	X.DeleteChar("Xn Ascalon")
	T.check("deleted: one", #X.Chars(), 1)
	T.check("deleted: Linen gone", (X.Owned(2589)), 0)
end)

T.scene("wealth: what to do with the things in your bags", function()
	local X = W.start()
	W.fill(0, {{2589, 20}, {2592, 10}, {14047, 5, nil, true}, {2840, 2}, {4306, 4}})
	W.advance(10)
	market(X)
	W.bagsChanged()
	local old = X.SaleRate
	X.SaleRate = nil
	local best = {}
	for _, r in ipairs(X.BagRows()) do best[r.key] = r end
	T.check("Linen: auction house", best["2589"] and best["2589"].best, "Auction house")
	T.near("Linen: AH value after the cut", best["2589"] and best["2589"].ah, 20 * 95)
	T.check("Linen: vendor value", best["2589"] and best["2589"].vendor, 20 * 13)
	T.check("Wool: a vendor pays more", best["2592"] and best["2592"].best, "Vendor")
	T.check("Runecloth: bound", best["14047"] and best["14047"].best, "Keep (bound)")
	T.check("Copper Bar: no auction price", best["2840"] and best["2840"].best, "Vendor")
	T.check("Silk: auction house", best["4306"] and best["4306"].best, "Auction house")
	T.check("sorted by value: 5 bound Runecloth (20s at a vendor) first", X.BagRows()[1].key, "14047")
	T.check("then Linen (19s)", X.BagRows()[2].key, "2589")
	-- slow sellers: Silk sells 0.1 a day and the auction house pays under 3 times the vendor: vendor
	X.SaleRate = function(key) return (key == "4306" or key == "2589") and 0.1 or 5 end
	best = {}
	for _, r in ipairs(X.BagRows()) do best[r.key] = r end
	T.check("slow Silk (2.85s vs 1.5s): vendor", best["4306"] and best["4306"].best, "Vendor")
	T.check("slow Linen (95c vs 13c): still the auction house", best["2589"] and best["2589"].best, "Auction house")
	T.check("sales speed shown", best["4306"] and best["4306"].rate, 0.1)
	X.SaleRate = old
end)

T.scene("ledger and wealth on the gold tab: every view shown with data", function()
	local X = W.start()
	W.fill(0, {{2589, 20}})
	W.advance(10)
	market(X)
	W.addMail(W.mailSold(2589, 1000, 20, "Ann Lee", 50))
	W.addMail(W.mailExpired(2592, 5))
	W.openMail()
